def find_city_coords_fallback(city_name):
    """
    Fallback: ищет координаты города во встроенном списке.
    Возвращает (lat, lon) или None.
    """
    if not city_name:
        return None
    
    city_lower = city_name.lower().strip()
    
    # Точное совпадение
    if city_lower in RUSSIAN_CITIES:
        coords = RUSSIAN_CITIES[city_lower]
        return coords['lat'], coords['lon']
    
    # Частичное совпадение
    for name, coords in RUSSIAN_CITIES.items():
        if name.startswith(city_lower) or city_lower.startswith(name):
            return coords['lat'], coords['lon']
    
    return None